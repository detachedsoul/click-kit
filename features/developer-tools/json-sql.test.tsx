import { cleanup, fireEvent, render, screen } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { afterEach, describe, expect, it } from "vitest";
import { JsonSqlTool } from "@/features/developer-tools/json-sql-tool";
import { createTableFromJson, jsonToSqlInsert } from "@/features/developer-tools/json-sql-utils";

afterEach(cleanup);

describe("JSON to SQL generator", () => {
	it("builds multi-row INSERT statements with union columns", () => {
		const sql = jsonToSqlInsert('[{"id":1,"name":"Ada"},{"id":2,"active":true}]', { table: "users" });
		expect(sql).toContain('INSERT INTO "users" ("id", "name", "active")');
		expect(sql).toContain("(1, 'Ada', NULL)");
		expect(sql).toContain("(2, NULL, TRUE)");
	});

	it("escapes quotes and serialises nested values", () => {
		const sql = jsonToSqlInsert(`[{"name":"O'Hara","meta":{"plan":"pro"}}]`, { table: "people" });
		expect(sql).toContain("'O''Hara'");
		expect(sql).toContain("'{\"plan\":\"pro\"}'");
	});

	it("follows each dialect's identifier, boolean, and null rules", () => {
		const mysql = jsonToSqlInsert('[{"ok":true,"name":"x"}]', { table: "t", dialect: "mysql" });
		expect(mysql).toContain("INSERT INTO `t` (`ok`, `name`)");
		expect(mysql).toContain("(1, 'x')");
		const sqlite = jsonToSqlInsert('[{"ok":false}]', { table: "t", dialect: "sqlite" });
		expect(sqlite).toContain("(FALSE)");
	});

	it("supports a single object and a commented header", () => {
		expect(jsonToSqlInsert('{"a":1}', { table: "t", multiRow: false })).toContain("-- Generated by ClickKit");
		expect(jsonToSqlInsert('{"a":1}', { table: "t" })).toContain("VALUES\n  (1);");
	});

	it("infers CREATE TABLE types", () => {
		const ddl = createTableFromJson('[{"id":1,"score":2.5,"name":"A","ok":true,"meta":{"a":1}}]', { table: "things" });
		expect(ddl).toContain('CREATE TABLE "things" (');
		expect(ddl).toContain('"id" BIGINT');
		expect(ddl).toContain('"score" DOUBLE PRECISION');
		expect(ddl).toContain('"name" TEXT');
		expect(ddl).toContain('"ok" BOOLEAN');
		expect(ddl).toContain('"meta" JSONB');
		expect(createTableFromJson('[{"ok":true}]', { table: "t", dialect: "sqlite" })).toContain('"ok" INTEGER');
	});

	it("rejects bad input, unsafe table names, and non-object rows", () => {
		expect(() => jsonToSqlInsert(" ")).toThrow(/Paste JSON/u);
		expect(() => jsonToSqlInsert("{oops")).toThrow(/Invalid JSON/u);
		expect(() => jsonToSqlInsert("42")).toThrow(/object or an array/u);
		expect(() => jsonToSqlInsert("[]")).toThrow(/at least one object/u);
		expect(() => jsonToSqlInsert("[1,2]")).toThrow(/Row 1 is not a JSON object/u);
		expect(() => jsonToSqlInsert("{}", { table: "bad table" })).toThrow(/identifier/u);
		expect(() => jsonToSqlInsert("{}")).toThrow(/at least one property/u);
	});

	it("renders INSERT output and switches to CREATE TABLE", async () => {
		const user = userEvent.setup();
		render(<JsonSqlTool />);
		expect((screen.getByLabelText("Result") as HTMLTextAreaElement).value).toContain('INSERT INTO "records"');
		fireEvent.change(screen.getByLabelText("Table name"), { target: { value: "people" } });
		expect((screen.getByLabelText("Result") as HTMLTextAreaElement).value).toContain('"people"');
		await user.click(screen.getByRole("button", { name: "CREATE TABLE" }));
		expect((screen.getByLabelText("Result") as HTMLTextAreaElement).value).toContain("CREATE TABLE");
	});
});
