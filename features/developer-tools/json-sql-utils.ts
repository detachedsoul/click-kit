const maximumSourceLength = 500_000;
const maximumRows = 5_000;

export type SqlDialect = "postgres" | "mysql" | "sqlite";

const quoteIdentifier = (name: string, dialect: SqlDialect) =>
	dialect === "mysql" ? `\`${name.replaceAll("`", "``")}\`` : `"${name.replaceAll('"', '""')}"`;

const quoteValue = (value: unknown, dialect: SqlDialect): string => {
	if (value === null || value === undefined) return "NULL";
	if (typeof value === "number") {
		if (!Number.isFinite(value)) throw new Error("JSON numbers must be finite to become SQL values.");
		return String(value);
	}
	if (typeof value === "boolean") {
		if (dialect === "mysql") return value ? "1" : "0";
		return value ? "TRUE" : "FALSE";
	}
	if (typeof value === "string") return `'${value.replaceAll("'", "''").replaceAll("\u0000", "")}'`;
	return `'${JSON.stringify(value).replaceAll("'", "''")}'`;
};

export type SqlOptions = { table?: string; dialect?: SqlDialect; multiRow?: boolean };

export const jsonToSqlInsert = (source: string, { table = "records", dialect = "postgres", multiRow = true }: SqlOptions = {}) => {
	if (!source.trim()) throw new Error("Paste JSON to build INSERT statements.");
	if (source.length > maximumSourceLength) throw new Error("Keep JSON input under 500,000 characters.");
	if (!/^[A-Za-z_][\w$]*(\.[A-Za-z_][\w$]*)?$/u.test(table.trim())) {
		throw new Error("Table names must be an identifier such as users or public.users.");
	}
	let value: unknown;
	try {
		value = JSON.parse(source) as unknown;
	} catch (error) {
		throw new Error(error instanceof Error ? `Invalid JSON: ${error.message}` : "Invalid JSON.");
	}
	if (value === null || typeof value !== "object") throw new Error("JSON must be an object or an array of objects to become rows.");
	const rows = Array.isArray(value) ? value : [value];
	if (rows.length === 0) throw new Error("Add at least one object to insert.");
	if (rows.length > maximumRows) throw new Error("Insert at most 5,000 rows at a time.");
	for (const [index, row] of rows.entries()) {
		if (row === null || typeof row !== "object" || Array.isArray(row)) throw new Error(`Row ${index + 1} is not a JSON object.`);
	}
	const records = rows as Record<string, unknown>[];
	const columns = [...new Set(records.flatMap((row) => Object.keys(row)))];
	if (columns.length === 0) throw new Error("Rows need at least one property to become a column.");
	const tableName = table.trim();
	const columnList = columns.map((column) => quoteIdentifier(column, dialect)).join(", ");
	const valuesFor = (row: Record<string, unknown>) => columns.map((column) => quoteValue(row[column] ?? null, dialect)).join(", ");
	const prefix = multiRow ? "INSERT INTO" : "-- Generated by ClickKit\nINSERT INTO";
	const header = `${prefix} ${quoteIdentifier(tableName, dialect)} (${columnList})`;
	if (!multiRow) {
		return `${header}\nVALUES\n${records.map((row) => `  (${valuesFor(row)})`).join(",\n")};\n`;
	}
	return `${header}\nVALUES\n${records.map((row) => `  (${valuesFor(row)})`).join(",\n")};\n`;
};

export const createTableFromJson = (source: string, { table = "records", dialect = "postgres" }: SqlOptions = {}) => {
	if (!source.trim()) throw new Error("Paste JSON to infer column types.");
	let value: unknown;
	try {
		value = JSON.parse(source) as unknown;
	} catch (error) {
		throw new Error(error instanceof Error ? `Invalid JSON: ${error.message}` : "Invalid JSON.");
	}
	const rows = (Array.isArray(value) ? value : [value]).filter((row): row is Record<string, unknown> => row !== null && typeof row === "object" && !Array.isArray(row));
	if (rows.length === 0) throw new Error("JSON must contain objects to infer columns.");
	const columns = [...new Set(rows.flatMap((row) => Object.keys(row)))];
	const typeFor = (column: string) => {
		const samples = rows.map((row) => row[column]).filter((item) => item !== null && item !== undefined);
		if (samples.length === 0) return dialect === "sqlite" ? "TEXT" : "TEXT";
		if (samples.every((item) => typeof item === "number")) return samples.every((item) => Number.isInteger(item)) ? (dialect === "sqlite" ? "INTEGER" : "BIGINT") : "DOUBLE PRECISION";
		if (samples.every((item) => typeof item === "boolean")) return dialect === "sqlite" ? "INTEGER" : "BOOLEAN";
		if (samples.every((item) => typeof item === "string")) return "TEXT";
		return dialect === "postgres" ? "JSONB" : "TEXT";
	};
	const lines = columns.map((column) => `  ${quoteIdentifier(column, dialect)} ${typeFor(column)}`);
	return `CREATE TABLE ${quoteIdentifier(table.trim(), dialect)} (\n${lines.join(",\n")}\n);\n`;
};
